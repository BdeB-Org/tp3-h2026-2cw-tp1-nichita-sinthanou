CREATE TABLE billet (
    id_billet NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    id_client NUMBER NOT NULL,
    id_vol NUMBER NOT NULL,
    classe VARCHAR2(100) NOT NULL,
    prix NUMBER(10, 2) NOT NULL,
    date_créé DATE DEFAULT SYSDATE NOT NULL,
    date_départ DATE NOT NULL,
    date_arrivé DATE NOT NULL,
    heure_départ VARCHAR(100),
    heure_arrivée VARCHAR(100),
    CONSTRAINT fk_client FOREIGN KEY (id_client) REFERENCES client(id_client),
    CONSTRAINT fk_vol FOREIGN KEY (id_vol) REFERENCES vol(id_vol)
);
