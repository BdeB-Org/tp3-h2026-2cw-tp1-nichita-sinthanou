CREATE TABLE vol (
    id_vol NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    id_avion NUMBER NOT NULL,
    code_iata_départ VARCHAR2(3) NOT NULL,
    code_iata_destination VARCHAR2(3) NOT NULL,
    durée_de_vol INTERVAL DAY TO SECOND,
    carburant_consommer NUMBER(10, 2),
    CONSTRAINT fk_avion FOREIGN KEY (id_avion) REFERENCES avion(id_avion),
    CONSTRAINT fk_départ FOREIGN KEY (code_iata_départ) REFERENCES départ(code_iata),
    CONSTRAINT fk_destination FOREIGN KEY (code_iata_destination) REFERENCES destination(code_iata)
);
